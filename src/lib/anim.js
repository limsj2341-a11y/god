export const VIEWPORT = { once: true, amount: 0.15, margin: '0px 0px -48% 0px' };

/**
 * 포인터가 정밀한 기기인지.
 *
 * 기울기·호버처럼 마우스가 있어야 뜻이 통하는 연출을 켤지 정할 때 쓴다.
 * 터치에서는 hover 가 "탭하고 나면 눌린 채로 남는" 상태가 되어 오히려 방해가 된다.
 * lib/motion.js 의 detectBlur 가 같은 판단을 하는데, 거기는 성능 이야기라
 * 목적이 달라 합치지 않았다.
 */
export function hasFinePointer() {
  if (typeof window === 'undefined' || !window.matchMedia) return false;
  return window.matchMedia('(pointer: fine)').matches;
}

/**
 * 막이 끝난 뒤 낱장이 넘어가는 데만 쓰는 스크롤 구간 (뷰포트 높이 대비).
 *
 * 이 구간이 없으면 앞 막의 마지막 글과 뒷 막의 첫 글이 넘김과 동시에 보인다.
 * 여기서는 글이 더 움직이지 않고 종이만 넘어가며, 다 넘어간 뒤에야
 * 뒷 막이 떠오른다 — 넘기고, 그다음에 읽는다.
 *
 * Page 는 이 길이만큼 자기 높이를 늘리고, BookStage 는 같은 구간에
 * 넘김 진행도를 건다. 두 곳이 같은 값을 봐야 어긋나지 않는다.
 */
export const TURN_RUNWAY = 0.9;

/**
 * 넘김 구간 안에서의 순서.
 *
 *   글이 걷히고 → 종이가 넘어가고 → 다음 글이 떠오른다.
 *
 * 처음에는 셋을 겹쳐 뒀는데, 그러면 종이가 아직 또렷한 글 위를 지나간다
 * (실측: 종이가 57% 넘어갈 때까지 앞 막이 opacity 1.00 이었다).
 * 책장을 넘길 때 글자가 종이에 비쳐 끌려가는 것처럼 보여 어색했다.
 * 서로 겹치는 구간을 아주 조금만 남겨 이어지게 한다.
 *
 * 처음에는 셋을 아예 안 겹치게 떼어 놨는데(0.30 / 0.28~0.78 / 0.76),
 * 그러면 아무것도 없는 화면이 구간의 절반 가까이 이어져 넘김이 답답해졌다.
 * 지금은 paper 의 뒷부분과 fadeIn 을 크게 겹쳐 둔다. 종이가 절반쯤 돌면
 * 모로 서서 폭이 거의 없고 곧 왼쪽으로 빠지므로, 그 위로 글이 떠올라도
 * 가려지지 않는다.
 *
 * 구간 길이(TURN_RUNWAY)가 늘면 여기 비율은 그대로 두는 것이 맞다.
 * 걷히는 것을 늦추고 떠오르는 것을 당기면 빈 구간이 줄 것 같지만 반대다 —
 * 빈 구간은 (fadeIn 시작 − fadeOut 끝)이라, 0.16/0.32 를 0.12/0.30 으로
 * 바꾸면 그 차가 0.16 에서 0.18 로 오히려 커진다. 한 번 그렇게 고쳐 놓고
 * 줄었다고 착각했다.
 *
 * Page 가 fadeOut/fadeIn 을, BookStage 가 paper 를 읽는다.
 * 세 값이 한 곳에 있어야 순서가 어긋나지 않는다.
 */
export const TURN_PHASE = {
  /** 앞 막의 글이 걷힌다 */
  fadeOut: [0, 0.16],
  /** 종이가 넘어간다 */
  paper: [0.12, 0.55],
  /** 뒷 막의 글이 떠오른다 — 종이가 모로 서는 순간부터 */
  fadeIn: [0.32, 0.68],
};

/**
 * 넘김 구간의 몇 할이 지나면 글이 다시 움직이기 시작하는지.
 *
 * 1 이면 구간이 완전히 끝나야 글이 움직인다. 그런데 종이는 55% 에 이미 다
 * 넘어가고 글도 68% 면 다 떠올라서, 남은 3분의 1 은 아무 일도 없이 굴리는
 * 구간이 된다 — 넘김이 끝났는데 다음 막이 안 따라오는 것처럼 느껴진다.
 *
 * 글이 다 떠오르는 지점(fadeIn 의 끝)에 맞춰 두면 그 텀이 없어진다.
 * Page 가 스크롤 길이와 진행도를 모두 이 값 기준으로 잡는다.
 */
export const TURN_READ_START = 0.7;
